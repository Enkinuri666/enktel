#!/usr/bin/env node
/**
 * Derive the relay's allowlist from the lineup it has to serve.
 *
 * The relay refuses any host not on its list, and that list is the whole
 * security model: an unrestricted proxy is an open proxy, and anyone who finds
 * the endpoint can bill their traffic to us. But the list held only the two
 * panel hosts, so relaying anything in the free lineup — which is where the
 * geo-blocks actually are — was refused before it left our own origin.
 *
 * The middle ground is this: allow exactly the hosts our own published lineup
 * points at, and nothing else. Bounded, auditable, regenerated whenever the
 * lineup is, and never an open proxy.
 *
 * Writes a generated module rather than reading the playlist at runtime: a
 * serverless function should not parse a 700 KB file on every request, and a
 * committed list is reviewable in a diff.
 *
 *   node scripts/gen-relay-hosts.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";

const PLAYLIST = "public/playlists/enktel-lineup.m3u";
const OUT = "src/lib/relay-hosts.generated.ts";

const text = readFileSync(PLAYLIST, "utf8");

const hosts = new Set();
for (const line of text.split("\n")) {
  const url = line.trim();
  if (!url.startsWith("http://") && !url.startsWith("https://")) continue;
  let host;
  try {
    host = new URL(url).hostname.toLowerCase();
  } catch {
    continue;
  }
  // A bare address on the list would let the relay be pointed at an address
  // rather than a name, which is the shape every SSRF filter bypass takes.
  // The route blocks private ranges separately; this keeps them off the
  // allowlist in the first place.
  if (/^[\d.]+$/.test(host) || host.includes(":")) continue;
  if (!host.includes(".")) continue;
  hosts.add(host);
}

const sorted = [...hosts].sort();

const body = `// Generated by scripts/gen-relay-hosts.mjs — do not edit by hand.
//
// Every host the published lineup points at, and nothing else. Regenerate with
// \`npm run gen:relay-hosts\` whenever the lineup changes; a host that is not
// here cannot be relayed, and a channel on it stays geo-blocked.
//
// ${sorted.length} hosts, from ${PLAYLIST}.

export const LINEUP_RELAY_HOSTS: readonly string[] = [
${sorted.map((h) => `  ${JSON.stringify(h)},`).join("\n")}
];
`;

writeFileSync(OUT, body);
console.log(`${OUT}: ${sorted.length} hosts from ${PLAYLIST}`);
